// Generates the pre-rendered icon modules used by src/components/ui/Icon.astro.
// Run before `astro build` (wired into package.json "build"). It scans the
// codebase/data for `tabler:<name>` usages, keeps only those that actually
// resolve in @iconify-json/tabler (skipping malformed/missing ones like the
// literal `tabler:brand-` or `tabler:waves`/`tabler:molecules`), and writes:
//   - src/components/ui/icon-valid-names.ts  (Set of resolvable names)
//   - src/components/ui/icon-svgs.ts         (name -> inline <svg> markup)
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');

const { getIconData, iconToSVG } = require(path.join(ROOT, 'node_modules/@iconify/utils/lib/index.cjs'));
const tabler = require(path.join(ROOT, 'node_modules/@iconify-json/tabler')).icons;

function resolvesIcon(collection, iconName) {
  let cur = iconName;
  const seen = new Set();
  let depth = 0;
  while (depth++ < 30) {
    if (seen.has(cur)) return false;
    seen.add(cur);
    const def = collection.icons[cur] ?? collection.aliases[cur];
    if (!def) return false;
    if (typeof def.body === 'string' && def.body.length > 0) return true;
    if (typeof def.parent === 'string') {
      cur = def.parent;
      continue;
    }
    return true;
  }
  return false;
}

const used = new Set();
function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const fp = path.join(dir, e.name);
    if (e.isDirectory()) {
      walk(fp);
      continue;
    }
    if (!/\.(astro|ts|tsx|js|jsx|json|md|mdx|html)$/.test(e.name)) continue;
    const txt = fs.readFileSync(fp, 'utf8');
    const re = /tabler:[a-zA-Z0-9_-]+/g;
    let m;
    while ((m = re.exec(txt)) !== null) used.add(m[0]);
  }
}
for (const d of ['src', 'public/data']) {
  const full = path.join(ROOT, d);
  if (fs.existsSync(full)) walk(full);
}

const valid = [];
const broken = [];
for (const name of used) {
  const iconName = name.split(':')[1];
  if (resolvesIcon(tabler, iconName)) valid.push(name);
  else broken.push(name);
}
valid.sort();
broken.sort();

const SRC_UI = path.join(ROOT, 'src/components/ui');

const validOut = `// AUTO-GENERATED by scripts/gen-icon-svgs.cjs — do not edit by hand.
// Set of icon names referenced in the codebase/data that actually resolve in
// @iconify-json/tabler. Used by src/components/ui/Icon.astro to skip any name
// that would make astro-icon recurse/crash during a static prerender.
export const VALID_ICON_NAMES = new Set([
${valid.map((n) => `  ${JSON.stringify(n)}`).join(',\n')},
]);

export const BROKEN_ICON_NAMES = [
${broken.map((n) => `  ${JSON.stringify(n)}`).join(',\n')},
];
`;

const svgs = {};
for (const name of valid) {
  const iconName = name.split(':')[1];
  const data = getIconData(tabler, iconName);
  if (!data) continue;
  const { attributes, body } = iconToSVG(data);
  const attrs = Object.entries(attributes)
    .map(([k, v]) => `${k}="${v}"`)
    .join(' ');
  svgs[name] = `<svg xmlns="http://www.w3.org/2000/svg" ${attrs}>${body}</svg>`;
}

const svgOut = `// AUTO-GENERATED by scripts/gen-icon-svgs.cjs — do not edit by hand.
// Pre-rendered SVG markup for every icon referenced in the site, so the
// <Icon /> component can inline them at build time without depending on
// astro-icon's runtime (which recurses/crashes during a static prerender).
export const ICON_SVGS: Record<string, string> = {
${Object.entries(svgs)
  .map(([n, s]) => `  ${JSON.stringify(n)}: ${JSON.stringify(s)},`)
  .join('\n')}
};
`;

fs.writeFileSync(path.join(SRC_UI, 'icon-valid-names.ts'), validOut);
fs.writeFileSync(path.join(SRC_UI, 'icon-svgs.ts'), svgOut);
console.log('Generated', valid.length, 'icon SVGs; skipped', broken.length, 'broken:', broken.join(', '));
