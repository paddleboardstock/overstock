#!/usr/bin/env node
/**
 * translate-faq-l10n.mjs
 *
 * `/{lang}/faq/` renders `FAQS_BY_LANG[lang]` from `src/lib/faq-l10n.ts`. Only the
 * five hand-curated locales exist there (en/de/es/fr/it), so every other locale
 * shows the English Q&A and the page is canonical-folded to `/faq/`.
 *
 * This script machine-translates the 40 English records (question + answer; `id`,
 * `category`, `relatedProducts` and `relatedGuides` stay verbatim) plus the page
 * title/description, and writes `src/lib/faq-l10n-mt.ts`. The page prefers the
 * hand-maintained map at runtime, so nothing curated is overwritten.
 *
 * Usage:
 *   node scripts/translate-faq-l10n.mjs                 # translate + emit
 *   node scripts/translate-faq-l10n.mjs --langs=bg,ko   # subset
 *   node scripts/translate-faq-l10n.mjs --dry-run       # no API calls
 *   node scripts/translate-faq-l10n.mjs --emit-only     # rewrite the file from cache
 *   node scripts/translate-faq-l10n.mjs --force         # ignore cached translations
 *
 * Requires Node >= 22.18 (native TypeScript type stripping) to import the EN source.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createEngine, fixTokenSpacing } from './lib/translate-lib.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LANGS_ALL = 'bg et he hr hu id ko lt lv ms ro sk sl sr th tl tr'.split(' ');
const CACHE_FILE = path.resolve(ROOT, '.cache', 'faq-cache.json');
const OUT_JSON = path.resolve(ROOT, '.cache', 'faq-out.json');
const OUT_TS = path.resolve(ROOT, 'src/lib/faq-l10n-mt.ts');
const EN_SRC = path.resolve(ROOT, 'src/lib/faq-l10n.ts');

const argOf = (n) => {
  const a = process.argv.find((s) => s.startsWith(`--${n}=`));
  return a ? a.slice(n.length + 3) : null;
};
const LANGS = (argOf('langs') || LANGS_ALL.join(','))
  .split(',')
  .map((s) => s.trim())
  .filter(Boolean);
const DRY_RUN = process.argv.includes('--dry-run');
const EMIT_ONLY = process.argv.includes('--emit-only');
const FORCE = process.argv.includes('--force');

const PAGE_TITLE_EN = 'Frequently asked questions';
const PAGE_DESC_EN =
  'Frequently asked questions about inflatable SUP boards, kayaks, dinghies, RIBs, safety equipment, and water sports.';

/** MT output is inserted into JSX text nodes — strip pseudo tags Bing sometimes injects. */
const sanitizeText = (s) =>
  String(s)
    .replace(/<\/?[A-Za-z][^>]{0,120}>/g, '')
    .trim();

async function loadEn() {
  const mod = await import(pathToFileURL(EN_SRC).href);
  const en = mod.FAQS_BY_LANG?.en;
  if (!Array.isArray(en) || !en.length) throw new Error('FAQS_BY_LANG.en not found');
  return en;
}

async function translateUnits(engine, units, lang) {
  const list = [...units];
  const map = new Map();
  const { batchChars, batchLines } = engine.opts;
  for (let i = 0; i < list.length;) {
    const chunk = [];
    let chars = 0;
    while (
      i < list.length &&
      (chunk.length === 0 || (chunk.length < batchLines && chars + list[i].length + 1 <= batchChars))
    ) {
      chars += list[i].length + 1;
      chunk.push(list[i]);
      i++;
    }
    const out = await engine.translateBatch(chunk, lang);
    chunk.forEach((t, k) => map.set(t, out[k]));
  }
  return map;
}

function emit(data, en) {
  // Emit every cached locale (not just --langs) so a subset run never drops the rest.
  const lanes = Object.keys(data).filter((l) => data[l]);
  const faqs = {};
  const meta = {};
  for (const lang of lanes) {
    faqs[lang] = en.map((item, i) => ({
      ...item,
      question: sanitizeText(fixTokenSpacing(data[lang].items[i].q)) || item.question,
      answer: sanitizeText(fixTokenSpacing(data[lang].items[i].a)) || item.answer,
    }));
    meta[lang] = {
      title: sanitizeText(fixTokenSpacing(data[lang].meta.title)) || PAGE_TITLE_EN,
      description: sanitizeText(fixTokenSpacing(data[lang].meta.description)) || PAGE_DESC_EN,
    };
  }
  const body = [
    '/**',
    ' * Machine translations for the FAQ page (`/{lang}/faq/`).',
    ' *',
    ' * Generated by `scripts/translate-faq-l10n.mjs` from the English records in',
    ' * `src/lib/faq-l10n.ts`; `id`, `category`, `relatedProducts` and `relatedGuides`',
    ' * are copied verbatim so links and category labels keep working. The page prefers',
    ' * the hand-maintained map, so curated locales are untouched.',
    ' */',
    "import type { FaqRecord } from '~/data/faq';",
    '',
    'export const FAQS_BY_LANG_MT: Record<string, FaqRecord[]> = ' +
      JSON.stringify(faqs, null, 2).replace(/\n/g, '\n') +
      ';',
    '',
    'export const FAQ_PAGE_META_MT: Record<string, { title: string; description: string }> = ' +
      JSON.stringify(meta, null, 2) +
      ';',
    '',
  ].join('\n');
  fs.writeFileSync(OUT_TS, body, 'utf8');
  return lanes;
}

async function main() {
  const en = await loadEn();
  let data = fs.existsSync(OUT_JSON) ? JSON.parse(fs.readFileSync(OUT_JSON, 'utf8')) : {};
  if (FORCE) for (const l of LANGS) delete data[l];

  if (!EMIT_ONLY) {
    const engine = createEngine({ cacheFile: CACHE_FILE, dryRun: DRY_RUN, log: console.log });
    engine.load();
    const units = new Set([PAGE_TITLE_EN, PAGE_DESC_EN]);
    for (const f of en) {
      units.add(f.question);
      units.add(f.answer);
    }
    console.log(`faq records=${en.length} units=${units.size} langs=${LANGS.join(',')} cache=${engine.cacheSize}`);
    if (!DRY_RUN) {
      await engine.refreshSession();
      console.log('Bing session ok');
    }
    const t0 = Date.now();
    for (const lang of LANGS) {
      const a0 = engine.stats.apiCalls;
      const map = await translateUnits(engine, units, lang);
      const tr = (s) => sanitizeText(fixTokenSpacing(map.get(s) ?? s)) || s;
      data[lang] = {
        items: en.map((f) => ({ q: tr(f.question), a: tr(f.answer) })),
        meta: { title: tr(PAGE_TITLE_EN), description: tr(PAGE_DESC_EN) },
      };
      engine.save();
      if (!DRY_RUN) fs.writeFileSync(OUT_JSON, JSON.stringify(data), 'utf8');
      console.log(`  ${lang}: ${en.length} records, api=${engine.stats.apiCalls - a0}`);
    }
    console.log(`translate done in ${Math.round((Date.now() - t0) / 1000)}s (api=${engine.stats.apiCalls})`);
  }

  if (!DRY_RUN) {
    const lanes = emit(data, en);
    console.log(`faq-l10n-mt.ts written: ${lanes.length} locales -> ${path.relative(ROOT, OUT_TS)}`);
  }
}

main().catch((e) => {
  console.error('FATAL:', e.message);
  process.exit(1);
});
