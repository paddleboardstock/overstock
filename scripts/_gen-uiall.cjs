const fs = require('fs');
const path = require('path');
const ROOT = process.cwd();
const GENERATED_DIR = path.join(ROOT, 'src/i18n/generated');
const UI_DIR = path.join(GENERATED_DIR, 'ui');

const ui = JSON.parse(fs.readFileSync('public/data/i18n-config.json', 'utf8'));
const langs = Object.keys(ui);

fs.mkdirSync(UI_DIR, { recursive: true });

const enUi = ui.en || {};

for (const l of langs) {
  const filePath = path.join(UI_DIR, l + '.ts');
  // Per-key EN fallback: partial dicts inherit missing keys from EN at generation
  // time, so components never see undefined for untranslated UI strings.
  const merged = l === 'en' ? enUi : { ...enUi, ...ui[l] };
  const content = '// AUTO-GENERATED\n// @ts-nocheck\nexport default ' + JSON.stringify(merged) + ';\n';
  fs.writeFileSync(filePath, content);
}
console.log('wrote ui/*.ts for', langs.length, 'languages');

let s = '// AUTO-GENERATED by scripts/_gen-uiall.cjs\n// @ts-nocheck\n';
for (const l of langs) {
  s += 'import _' + l + " from './ui/" + l + ".ts';\n";
}
s += '\nconst map: Record<string, any> = {\n';
for (const l of langs) {
  s += '  ' + JSON.stringify(l) + ': _' + l + ',\n';
}
s += '};\n';
s += 'export function getUiForLang(lang: string): any {\n  return (lang && map[lang]) || map.en || {};\n}\n';
fs.writeFileSync(path.join(GENERATED_DIR, 'ui-all.ts'), s);
console.log('wrote ui-all.ts with', langs.length, 'static imports');
