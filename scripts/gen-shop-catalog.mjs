// Generates workers/shared/catalog.ts — the server-side price source of truth
// for the shop-worker. Prices are pulled from the 13 product MDX frontmatters
// (src/content/products/*.mdx). Run via `npm run gen:shop-catalog` or the
// build pipeline whenever a product price changes.
//
// IMPORTANT: never trust client-submitted prices — the worker always
// recomputes order totals from this generated catalog.
import fs from 'node:fs';
import path from 'node:path';
import { globSync } from 'glob';
import * as yaml from 'js-yaml';

const PRODUCTS_DIR = 'src/content/products';
const OUT_FILE = 'workers/shared/catalog.ts';

function parseFrontmatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) return null;
  return yaml.load(match[1]);
}

function toCents(amount) {
  const n = Number(String(amount ?? '').replace(/[^0-9.]/g, ''));
  if (!Number.isFinite(n) || n <= 0) return null;
  return Math.round(n * 100);
}

const files = globSync(`${PRODUCTS_DIR}/*.{md,mdx}`).sort();
const entries = [];

for (const file of files) {
  const raw = fs.readFileSync(file, 'utf8');
  const fm = parseFrontmatter(raw);
  if (!fm || fm.draft) continue;
  const priceCents = toCents(fm.price?.amount);
  if (!priceCents) continue; // products without a price are not sellable
  entries.push({
    slug: path.basename(file).replace(/\.(md|mdx)$/i, ''),
    title: String(fm.title || path.basename(file)),
    priceCents,
    currency: String(fm.price?.currency || 'USD'),
    image: String(fm.image || ''),
    inStock: fm.inStock !== false,
  });
}

if (entries.length === 0) {
  console.error(`[gen-shop-catalog] no sellable products found in ${PRODUCTS_DIR}/`);
  process.exit(1);
}

const banner = `// AUTO-GENERATED by scripts/gen-shop-catalog.mjs — DO NOT EDIT BY HAND.
// Source of truth: src/content/products/*.mdx frontmatter (price/inStock).
// Regenerate with: npm run gen:shop-catalog
`;

const body = entries
  .map(
    (e) =>
      `  {\n    slug: '${e.slug.replace(/'/g, "\\'")}',\n    title: '${e.title.replace(/'/g, "\\'")}',\n    priceCents: ${e.priceCents},\n    currency: '${e.currency}',\n    image: '${e.image.replace(/'/g, "\\'")}',\n    inStock: ${e.inStock},\n  },`
  )
  .join('\n');

const out = `${banner}
export interface CatalogEntry {
  slug: string;
  title: string;
  priceCents: number;
  currency: string;
  image: string;
  inStock: boolean;
}

export const SHOP_CATALOG: CatalogEntry[] = [
${body}
];

export const CATALOG_BY_SLUG: Record<string, CatalogEntry> = Object.fromEntries(
  SHOP_CATALOG.map((entry) => [entry.slug, entry])
);

export const FREE_SHIPPING_THRESHOLD_CENTS = 30000;
export const SHIPPING_FLAT_CENTS = 3900;

export function shippingCostCents(subtotalCents: number): number {
  if (subtotalCents <= 0) return 0;
  return subtotalCents >= FREE_SHIPPING_THRESHOLD_CENTS ? 0 : SHIPPING_FLAT_CENTS;
}
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, out, 'utf8');
console.log(`[gen-shop-catalog] wrote ${OUT_FILE} (${entries.length} products)`);
