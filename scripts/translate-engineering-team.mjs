#!/usr/bin/env node
/**
 * translate-engineering-team.mjs
 *
 * `/{lang}/engineering-team/` renders `TEAM_MEMBERS` / `RESEARCH_AREAS` from
 * `src/lib/engineering-team-l10n.ts`, which only ships the five hand-curated
 * locales (en/de/es/fr/it). Every other locale falls back to English copy.
 *
 * This script machine-translates the member roles, experience, expertise bullets and
 * research areas (person names stay verbatim) and writes
 * `src/lib/engineering-team-l10n-mt.ts`. The page prefers the curated map at runtime.
 *
 * Usage:
 *   node scripts/translate-engineering-team.mjs                 # translate + emit
 *   node scripts/translate-engineering-team.mjs --langs=bg,ko   # subset
 *   node scripts/translate-engineering-team.mjs --dry-run       # no API calls
 *   node scripts/translate-engineering-team.mjs --emit-only     # rewrite from cache
 *   node scripts/translate-engineering-team.mjs --force         # ignore cached data
 *
 * Requires Node >= 22.18 (native TypeScript type stripping) to import the EN source.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createEngine, fixTokenSpacing } from './lib/translate-lib.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LANGS_ALL = 'bg et he hr hu id ko lt lv ms ro sk sl sr th tl tr'.split(' ');
const CACHE_FILE = path.resolve(ROOT, '.cache', 'engineering-team-cache.json');
const OUT_JSON = path.resolve(ROOT, '.cache', 'engineering-team-out.json');
const OUT_TS = path.resolve(ROOT, 'src/lib/engineering-team-l10n-mt.ts');
const EN_SRC = path.resolve(ROOT, 'src/lib/engineering-team-l10n.ts');

const argOf = (n) => {
  const a = process.argv.find((s) => s.startsWith(`--${n}=`));
  return a ? a.slice(n.length + 3) : null;
};
const LANGS = (argOf('langs') || LANGS_ALL.join(','))
  .split(',')
  .map((s) => s.trim())
  .filter(Boolean);
const DRY_RUN = process.argv.includes('--dry-run');
const EMIT_ONLY = process.argv.includes('--emit-only');
const FORCE = process.argv.includes('--force');

const sanitizeText = (s) =>
  fixTokenSpacing(
    String(s)
      .replace(/<\/?[A-Za-z][^>]{0,120}>/g, '')
      .trim()
  );

/** The hardcoded discipline tags in the hero of `/{lang}/engineering-team/`. */
const DISCIPLINES_EN = [
  'Materials Science',
  'Product Design',
  'Quality Engineering',
  'OEM Programs',
  'RIB Fabrication',
];

async function loadEn() {
  const mod = await import(pathToFileURL(EN_SRC).href);
  const members = mod.TEAM_MEMBERS?.en;
  const areas = mod.RESEARCH_AREAS?.en;
  if (!Array.isArray(members) || !Array.isArray(areas)) throw new Error('EN engineering-team data not found');
  return { members, areas };
}

async function translateUnits(engine, units, lang) {
  const list = [...units];
  const map = new Map();
  const { batchChars, batchLines } = engine.opts;
  for (let i = 0; i < list.length;) {
    const chunk = [];
    let chars = 0;
    while (
      i < list.length &&
      (chunk.length === 0 || (chunk.length < batchLines && chars + list[i].length + 1 <= batchChars))
    ) {
      chars += list[i].length + 1;
      chunk.push(list[i]);
      i++;
    }
    const out = await engine.translateBatch(chunk, lang);
    chunk.forEach((t, k) => map.set(t, out[k]));
  }
  return map;
}

function emit(data, en) {
  // Emit every cached locale (not just --langs) so a subset run never drops the rest.
  const lanes = Object.keys(data).filter((l) => data[l]);
  const members = {};
  const areas = {};
  const disciplines = {};
  for (const lang of lanes) {
    members[lang] = en.members.map((m, i) => ({ ...m, ...data[lang].members[i] }));
    areas[lang] = en.areas.map((a, i) => ({ ...a, ...data[lang].areas[i] }));
    disciplines[lang] = data[lang].disciplines?.map((d, i) => sanitizeText(d) || DISCIPLINES_EN[i]) || DISCIPLINES_EN;
  }
  const body = [
    '/**',
    ' * Machine translations for `/{lang}/engineering-team/`.',
    ' *',
    ' * Generated by `scripts/translate-engineering-team.mjs` from the English records in',
    ' * `src/lib/engineering-team-l10n.ts`. Person names are kept verbatim; only role,',
    ' * experience, expertise bullets and the research areas are translated. The page',
    ' * prefers the hand-maintained map, so curated locales are untouched.',
    ' */',
    'export const TEAM_MEMBERS_MT: Record<string, any[]> = ' + JSON.stringify(members, null, 2) + ';',
    '',
    'export const RESEARCH_AREAS_MT: Record<string, any[]> = ' + JSON.stringify(areas, null, 2) + ';',
    '',
    'export const DISCIPLINES_MT: Record<string, string[]> = ' + JSON.stringify(disciplines, null, 2) + ';',
    '',
  ].join('\n');
  fs.writeFileSync(OUT_TS, body, 'utf8');
  return lanes;
}

async function main() {
  const en = await loadEn();
  let data = fs.existsSync(OUT_JSON) ? JSON.parse(fs.readFileSync(OUT_JSON, 'utf8')) : {};
  if (FORCE) for (const l of LANGS) delete data[l];

  if (!EMIT_ONLY) {
    const engine = createEngine({ cacheFile: CACHE_FILE, dryRun: DRY_RUN, log: console.log });
    engine.load();
    const units = new Set();
    for (const m of en.members) {
      units.add(m.role);
      units.add(m.experience);
      units.add(m.area);
      for (const e of m.expertise) units.add(e);
    }
    for (const a of en.areas) {
      units.add(a.title);
      units.add(a.desc);
    }
    for (const d of DISCIPLINES_EN) units.add(d);
    console.log(`members=${en.members.length} areas=${en.areas.length} units=${units.size} cache=${engine.cacheSize}`);
    if (!DRY_RUN) {
      await engine.refreshSession();
      console.log('Bing session ok');
    }
    const t0 = Date.now();
    for (const lang of LANGS) {
      const a0 = engine.stats.apiCalls;
      const map = await translateUnits(engine, units, lang);
      const tr = (s) => sanitizeText(map.get(s) ?? s) || s;
      data[lang] = {
        members: en.members.map((m) => ({
          role: tr(m.role),
          experience: tr(m.experience),
          expertise: m.expertise.map(tr),
          area: tr(m.area),
        })),
        areas: en.areas.map((a) => ({ title: tr(a.title), desc: tr(a.desc) })),
        disciplines: DISCIPLINES_EN.map(tr),
      };
      engine.save();
      if (!DRY_RUN) fs.writeFileSync(OUT_JSON, JSON.stringify(data), 'utf8');
      console.log(`  ${lang}: ${en.members.length} members, api=${engine.stats.apiCalls - a0}`);
    }
    console.log(`translate done in ${Math.round((Date.now() - t0) / 1000)}s (api=${engine.stats.apiCalls})`);
  }

  if (!DRY_RUN) {
    const lanes = emit(data, en);
    console.log(`engineering-team-l10n-mt.ts written: ${lanes.length} locales`);
  }
}

main().catch((e) => {
  console.error('FATAL:', e.message);
  process.exit(1);
});
