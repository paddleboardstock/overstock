// Generates seed SQL for the shop D1 database from the main repository's
// stock catalog (generated from the OneDrive xlsx source of truth).
//
// All products are imported as DRAFT with EXW wholesale prices as reference
// placeholders — an admin must set retail prices and activate them before
// anything becomes sellable.
//
// Usage:
//   node scripts/seed-stock.mjs [path-to-main-repo-stock-catalog.ts]
//   wrangler d1 execute paddleboardoverstock-shop-db --local \
//     --file seed-stock.sql --config workers/shop-api/wrangler.toml

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const defaultCatalog = resolve(scriptDir, '../../Overstock/workers/admin-worker/stock-catalog.ts');
const catalogPath = process.argv[2] ?? defaultCatalog;
const outputPath = resolve(scriptDir, '../seed-stock.sql');

// Images stay on the main site CDN for v0 (external_url strategy).
const MAIN_SITE_ORIGIN = 'https://paddleboardoverstock.com';

const source = readFileSync(catalogPath, 'utf8');
const marker = 'export const STOCK_CATALOG: StockCatalog = ';
const start = source.indexOf(marker);
if (start === -1) {
  console.error(`Could not find STOCK_CATALOG in ${catalogPath}`);
  process.exit(1);
}
const jsonStart = source.indexOf('{', start);
// The object literal ends at the last `};` in the file (include the `}`).
const jsonEnd = source.lastIndexOf('};') + 1;
const catalog = JSON.parse(source.slice(jsonStart, jsonEnd));

function sqlString(value) {
  if (value === null || value === undefined || value === '') return 'NULL';
  return `'${String(value).replace(/'/g, "''")}'`;
}

const statements = [];
let productCount = 0;
let variantCount = 0;
let imageCount = 0;

for (const section of catalog.sections) {
  for (const item of section.items) {
    const slug = `clearance-${item.id}`;
    const productId = `p-${item.id}`;
    const variantId = `v-${item.id}`;
    const title = `${item.dimensions} cm — ${section.title.replace(/Stock /i, '')} (clearance)`;
    const description = item.note ? `${item.note}\n\nDimensions: ${item.dimensions} cm. Warehouse clearance stock; limited quantity. Contact us for a shipping quote.` : `Dimensions: ${item.dimensions} cm. Warehouse clearance stock; limited quantity. Contact us for a shipping quote.`;

    statements.push(
      `INSERT INTO products (id, slug, status, brand, title, description) VALUES ('${productId}', '${slug}', 'draft', NULL, ${sqlString(title)}, ${sqlString(description)}) ON CONFLICT(id) DO NOTHING;`
    );
    productCount++;

    statements.push(
      `INSERT INTO product_variants (id, product_id, sku, variant_name, currency, price_cents, active) VALUES ('${variantId}', '${productId}', '${item.id.toUpperCase()}', ${sqlString(item.dimensions + ' cm')}, 'usd', ${Math.round(item.priceUsd * 100)}, 1) ON CONFLICT(id) DO NOTHING;`
    );
    variantCount++;

    statements.push(
      `INSERT INTO inventory (variant_id, on_hand, reserved) VALUES ('${variantId}', ${Number(item.quantity) || 0}, 0) ON CONFLICT(variant_id) DO NOTHING;`
    );

    item.images.forEach((imagePath, index) => {
      const url = imagePath.startsWith('http') ? imagePath : `${MAIN_SITE_ORIGIN}${imagePath}`;
      statements.push(
        `INSERT INTO product_images (id, product_id, external_url, alt_text, sort_order) VALUES ('img-${item.id}-${index + 1}', '${productId}', ${sqlString(url)}, ${sqlString(title)}, ${index}) ON CONFLICT(id) DO NOTHING;`
      );
      imageCount++;
    });
  }
}

const header = `-- Generated by scripts/seed-stock.mjs from ${catalogPath}
-- Catalog updated: ${catalog.updatedAt} (${catalog.currency})
-- ALL PRODUCTS ARE DRAFT: set retail prices and activate via /api/admin before selling.
BEGIN TRANSACTION;
`;
const footer = `\nCOMMIT;\n`;

writeFileSync(outputPath, header + statements.join('\n') + footer, 'utf8');
console.log(`Wrote ${outputPath}`);
console.log(`  products:   ${productCount}`);
console.log(`  variants:   ${variantCount}`);
console.log(`  images:     ${imageCount}`);
console.log(`  sections:   ${catalog.sections.map((s) => `${s.id}(${s.items.length})`).join(', ')}`);
